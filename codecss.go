package main

import (
	"fmt"
	"io"
	"strings"

	"github.com/alecthomas/chroma/v2/formatters/html"
	"github.com/alecthomas/chroma/v2/styles"
)

// emitCodeCSS writes the syntax-highlighting stylesheet for both colour
// schemes. It is run by hand (`blogen -emit-code-css > site/templates/code.css`)
// and the result is committed, so a normal build needs no Chroma style lookup
// and the CSS can be reviewed in a diff like any other file.
//
// Chroma emits one flat rule set per style. Serving two themes therefore means
// generating it twice and scoping the dark copy the same way the rest of the
// site does: the media query for visitors who never touched the toggle, plus an
// explicit [data-theme] rule that wins in either direction.
func emitCodeCSS(w io.Writer) error {
	light, err := chromaRules("github")
	if err != nil {
		return err
	}
	dark, err := chromaRules("github-dark")
	if err != nil {
		return err
	}

	fmt.Fprint(w, "/* Syntax highlighting. Generated by `blogen -emit-code-css` from the\n"+
		"   Chroma github / github-dark styles. Edit that command, not this file.\n"+
		"   Backgrounds are dropped on purpose: .post-body pre already paints one\n"+
		"   from the shared design tokens. */\n\n")

	for _, r := range light {
		fmt.Fprintln(w, r)
	}

	fmt.Fprint(w, "\n@media (prefers-color-scheme: dark) {\n")
	for _, r := range dark {
		fmt.Fprintf(w, "  :root:not([data-theme=\"light\"]) %s\n", r)
	}
	fmt.Fprint(w, "}\n\n")

	for _, r := range dark {
		fmt.Fprintf(w, ":root[data-theme=\"dark\"] %s\n", r)
	}
	return nil
}

// chromaRules renders one Chroma style and returns its rules, normalised to one
// selector per line and stripped of the wrapper backgrounds.
func chromaRules(name string) ([]string, error) {
	style := styles.Get(name)
	if style == nil || style.Name != name {
		return nil, fmt.Errorf("chroma style %q not found", name)
	}
	var buf strings.Builder
	f := html.New(html.WithClasses(true))
	if err := f.WriteCSS(&buf, style); err != nil {
		return nil, err
	}

	var out []string
	for _, line := range strings.Split(buf.String(), "\n") {
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		// drop Chroma's leading "/* Token */" comment
		if i := strings.Index(line, "*/"); strings.HasPrefix(line, "/*") && i >= 0 {
			line = strings.TrimSpace(line[i+2:])
		}
		if line == "" {
			continue
		}
		// .bg is the standalone background block; .chroma is the pre wrapper.
		// Both only carry colours we already own via the design tokens.
		if strings.HasPrefix(line, ".bg ") || strings.HasPrefix(line, ".chroma {") {
			continue
		}
		if !strings.HasPrefix(line, ".chroma") {
			continue
		}
		out = append(out, line)
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("chroma style %q produced no rules", name)
	}
	return out, nil
}
